-- The runtime every quest made with Conjunction calls (setup.py: install_runtime): the scripts (Cj*) as their own mod
-- in the game, its version in runtime.txt, the item name lookup made from this game's catalog when there is one
-- (assets.write_item_script), else the one that comes with Conjunction. The game's own plug-ins' runtime scripts need
-- the app (their Python): the game has none.
--   SU.install_runtime(cfg) -> the scripts' folder     SU.installed_runtime(cfg) -> its version (0: none)
local CFG = require("conjunction.config")
local PATHS = require("conjunction.paths")
local FS = require("conjunction.fsutil")
local PYS = require("conjunction.pystr")
local SU = {}

SU.RUNTIME_VERSION = 2              -- packaging.RUNTIME_VERSION
SU.RUNTIME_MOD, SU.EDITOR_MOD = "modConjunctionRuntime", "modConjunction"
SU.RUNTIME_MARK = "runtime.txt"
SU.ITEM_SCRIPT = "conjunction_items.ws"

function SU.installed_runtime(cfg)
  cfg = cfg or CFG.load()
  local s = w3.fs.read(PATHS.join(cfg.game or "", "Mods", SU.RUNTIME_MOD, SU.RUNTIME_MARK))
  local v = s and s:match("^%s*([+-]?%d+)%s*$")
  return v and tonumber(v) or 0
end

local function runtime_names()
  local names = {}
  for _, f in ipairs(FS.walk(PATHS.RUNTIME_SCRIPTS)) do names[PYS.lower(f.rel)] = true end
  return names
end
-- scripts in the installed mod it no longer has there (a removed script would still be compiled - twice)
local function leftovers(dst, keep)
  if not w3.fs.isdir(dst) then return {} end
  local out = {}
  for _, f in ipairs(FS.walk(dst)) do
    if f.name:sub(-3) == ".ws" and not keep[PYS.lower(f.rel)] then out[#out + 1] = f.path end
  end
  return out
end

-- assets.shipped_names: the names Conjunction's own item table holds for CjItemName / CjLootName
function SU.shipped_names(fn)
  local text = FS.read_text(PATHS.RUNTIME_SCRIPTS .. "\\local\\" .. SU.ITEM_SCRIPT)
  if not text then return {} end
  local seen, out = {}, {}
  local at = 1
  while true do
    local s, e = text:find("function " .. fn .. "%d+%(s : string%) : name {", at)
    if not s then break end
    local close = text:find("\n}", e + 1, true)
    if not close then break end
    for n in text:sub(e + 1, close - 1):gmatch('if %(s == "([^"]+)"%)') do
      if not seen[n] then seen[n] = true out[#out + 1] = n end
    end
    at = close + 2
  end
  table.sort(out)
  return out
end

local function chunked(out, fn, names)
  local ok = {}
  for _, n in ipairs(names) do if n:match("^[A-Za-z0-9 _]+$") then ok[#ok + 1] = n end end
  local chunks = {}
  for i = 1, #ok, 120 do
    local c = {}
    for k = i, math.min(i + 119, #ok) do c[#c + 1] = ok[k] end
    chunks[#chunks + 1] = c
  end
  for k, group in ipairs(chunks) do
    out[#out + 1] = string.format("function %s%d(s : string) : name {", fn, k - 1)
    for _, n in ipairs(group) do out[#out + 1] = string.format("    if (s == \"%s\") { return '%s'; }", n, n) end
    out[#out + 1] = "    return '';"
    out[#out + 1] = "}"
  end
  out[#out + 1] = string.format("function %s(s : string) : name {", fn)
  out[#out + 1] = "    var n : name;"
  for k = 1, #chunks do out[#out + 1] = string.format("    n = %s%d(s); if (n != '') { return n; }", fn, k - 1) end
  out[#out + 1] = "    return '';"
  out[#out + 1] = "}"
  out[#out + 1] = ""
end

-- assets.write_item_script: conjunction_items.ws - CjItemName("Ruby dust") -> 'Ruby dust' (and the loot tables)
function SU.write_item_script(folder)
  local A = require("conjunction.assets")
  local ready = A.ready()
  local function from_db(sql)
    local DB = require("conjunction.db")
    local db = DB.open(A.DB, false)
    local out = {}
    for _, r in ipairs(db:rows(sql)) do out[#out + 1] = r.name end
    db:close()
    table.sort(out)
    return out
  end
  local names = ready and from_db("select name from items") or SU.shipped_names("CjItemName")
  local C = require("conjunction.content")
  local ok_packs, packs = pcall(C.installed_packs)
  local set, all = {}, {}
  for _, n in ipairs(names) do if not set[n] then set[n] = true all[#all + 1] = n end end
  for _, p in ipairs(ok_packs and packs or {}) do
    local items = C.pack_index(p).items
    for _, i in ipairs(type(items) == "table" and items or {}) do
      if type(i.name) == "string" and i.name ~= "" and not set[i.name] then
        set[i.name] = true
        all[#all + 1] = i.name
      end
    end
  end
  table.sort(all)
  local out = {"// generated by conjunction from this game's item definitions - an item's name as text -> the item's " ..
               "name"}
  chunked(out, "CjItemName", all)
  local loot = ready and from_db("select name from loot") or SU.shipped_names("CjLootName")
  chunked(out, "CjLootName", loot)
  local path = folder .. "\\" .. SU.ITEM_SCRIPT
  w3.fs.mkdir(folder)
  assert(FS.write_text(path, table.concat(out, "\n")))
  return path
end

-- a file written only when its content changes: a script's time says when it changed (SU.runtime_in_game)
local function put(data, path)
  if w3.fs.read(path) == data then return false end
  local function mkdirs(d)
    if d == "" or w3.fs.isdir(d) then return end
    mkdirs((d:gsub("[\\/][^\\/]*$", "")))
    w3.fs.mkdir(d)
  end
  mkdirs((path:gsub("[\\/][^\\/]*$", "")))
  assert(w3.fs.write(path, data))
  return true
end
-- src's files into dst, each written only when it changed (not the backups of a patch, not skip)
local function sync_tree(src, dst, skip)
  for _, f in ipairs(FS.walk(src)) do
    if not f.name:find(".bak", 1, true) and f.name ~= skip then
      put(assert(w3.fs.read(f.path)), dst .. "\\" .. f.rel)
    end
  end
end

function SU.install_runtime(cfg)
  cfg = cfg or CFG.load()
  local dst = PATHS.join(cfg.game, "Mods", SU.RUNTIME_MOD, "content", "scripts")
  local have = SU.installed_runtime(cfg)
  if have > SU.RUNTIME_VERSION then              -- (a newer one, the Nexus runtime: it serves every older quest)
    print(string.format("a newer Conjunction Runtime (%d) is in the game - kept", have))
    return dst
  end
  local A = require("conjunction.assets")
  local C = require("conjunction.content")
  local packs = false
  local ok, list = pcall(C.installed_packs, cfg.game)
  for _, p in ipairs(ok and list or {}) do
    local items = C.pack_index(p).items
    if type(items) == "table" and #items > 0 then packs = true end
  end
  local own_items = A.ready() or packs           -- (a pack's items join the table - also without a catalog)
  sync_tree(PATHS.RUNTIME_SCRIPTS, dst, own_items and SU.ITEM_SCRIPT or nil)   -- (made below: written once)
  for _, f in ipairs(FS.walk(dst)) do               -- (and none left from before)
    if f.name:find(".bak", 1, true) then w3.fs.remove(f.path) end
  end
  local before = SU.installed_runtime(cfg)
  assert(FS.write_text(PATHS.join(cfg.game, "Mods", SU.RUNTIME_MOD, SU.RUNTIME_MARK), SU.RUNTIME_VERSION .. "\n"))
  if before > 0 and before < SU.RUNTIME_VERSION then
    require("conjunction.updates").note(string.format("Conjunction Runtime updated to %d in the game (it was %d)",
                                                      SU.RUNTIME_VERSION, before))
  end
  for _, old in ipairs(leftovers(dst, runtime_names())) do w3.fs.remove(old) end
  if own_items then
    local tmp = (os.getenv("TEMP") or "C:\\tmp") .. "\\cj_items_" .. require("conjunction.marks").uuid4_hex():sub(1, 8)
    local made = SU.write_item_script(tmp)
    put(assert(w3.fs.read(made)), dst .. "\\local\\" .. SU.ITEM_SCRIPT)
    FS.rmtree(tmp)
  end
  return dst
end

-- when the running game started (TW3SE's out\session.txt: "started <date> <time>, pid ..."), as a time stamp; nil when
-- it does not say
function SU.game_started(cfg)
  cfg = cfg or CFG.load()
  local head = w3.fs.read(PATHS.join(cfg.game or "", "bin", "x64_dx12", "tw3se", "out", "session.txt")) or ""
  local y, mo, d, h, mi, se = head:match("^started (%d%d%d%d)%-(%d%d)%-(%d%d) (%d%d):(%d%d):(%d%d)")
  if not y then return nil end
  return os.time({year = tonumber(y), month = tonumber(mo), day = tonumber(d), hour = tonumber(h), min = tonumber(mi),
                  sec = tonumber(se)})
end

-- the runtime's scripts in the game as the running game compiled them at its start (none changed since) -> their
-- folder, or nil. Build & Play into the running game lets a quest call them (scriptlib.fits_runtime): no script of
-- its own, no restart (MaximdeWinter 23.10.)
function SU.runtime_in_game(cfg)
  cfg = cfg or CFG.load()
  local dst = PATHS.join(cfg.game or "", "Mods", SU.RUNTIME_MOD, "content", "scripts")
  local start = SU.game_started(cfg)
  if not start or not w3.fs.isdir(dst) then return nil end
  local newest
  for _, f in ipairs(FS.walk(dst)) do
    if f.name:sub(-3) == ".ws" then
      local t = w3.fs.mtime(f.path)
      if t and (not newest or t > newest) then newest = t end
    end
  end
  return (newest and newest < start) and dst or nil
end

return SU
